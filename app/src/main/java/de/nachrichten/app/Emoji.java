    static final String MRU_KEY = "reactMru";
    private static final String SEP = "\u0001";

    /** Wie viele Emojis in der Leiste erscheinen, bevor das Plus-Zeichen kommt. */
    static final int BAR = 7;

    private static String[] mruList(App app) {
        String s = app.prefs.getString(MRU_KEY, "");
        if (s.isEmpty()) return new String[0];
        return s.split(SEP, -1);
    }

    /** Ein verwendetes Emoji nach ganz vorne schieben (ohne Dubletten). */
    static void use(App app, String emoji) {
        if (emoji == null || emoji.isEmpty()) return;
        LinkedHashSet<String> set = new LinkedHashSet<>();
        set.add(emoji);
        for (String e : mruList(app)) if (!e.isEmpty()) set.add(e);
        List<String> list = new ArrayList<>(set);
        if (list.size() > 40) list = list.subList(0, 40);
        app.prefs.edit().putString(MRU_KEY, String.join(SEP, list)).apply();
    }

    /** Alle zuletzt verwendeten Emojis (für die „Zuletzt verwendet"-Reihe in der großen Auswahl). */
    static String[] recent(App app) {
        List<String> list = new ArrayList<>();
        for (String e : mruList(app)) if (!e.isEmpty()) list.add(e);
        return list.toArray(new String[0]);
    }

    /** Die ersten Emojis für die Leiste: zuletzt verwendete zuerst, mit Standard aufgefüllt. */
    static String[] bar(App app) {
        LinkedHashSet<String> set = new LinkedHashSet<>();
        for (String e : mruList(app)) if (!e.isEmpty()) set.add(e);
        for (String e : Base.REACTIONS) set.add(e);
        List<String> list = new ArrayList<>(set);
        if (list.size() > BAR) list = list.subList(0, BAR);
        return list.toArray(new String[0]);
    }

